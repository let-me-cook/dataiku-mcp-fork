import assert from 'node:assert/strict';
import {test} from 'node:test';
import {readFileSync,writeFileSync,readdirSync,existsSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {allTools,listTools} from '../dist/tool-registry.js';
import {denial,destructiveOptIn,intakeTools} from '../dist/tool-policy.js';
const here=dirname(fileURLToPath(import.meta.url));const server=join(here,'..');const root=join(server,'..');
const read=p=>readFileSync(p,'utf8');
const names=new Set(allTools.map(t=>t.name));
const byDefault=listTools({instanceType:'design',allowDestructive:false,intake:false}).length;
const auto={instanceType:'automation',allowDestructive:true,intake:true};
const row=t=>{
 const needs=destructiveOptIn.has(t.name)?'`DSS_ALLOW_DESTRUCTIVE`':intakeTools.has(t.name)?'`DSS_INTAKE_URL`':'';
 return `| \`${t.name}\` | ${t.annotations.readOnlyHint?'Read':'Write'} | ${denial(t,auto)?'Refused':'Allowed'} | ${needs} |`;
};
const expected=()=>{
 const reads=allTools.filter(t=>t.annotations.readOnlyHint).length;
 return ['<!-- generated by test/docs.test.mjs; run UPDATE_CAPABILITIES=1 make test -->',`**${byDefault} tools** by default and **${allTools.length} tools** with an intake backend: ${reads} read and ${allTools.length-reads} write.`,'','| Tool | Access | On an automation node | Needs |','| --- | --- | --- | --- |',...[...allTools].sort((a,b)=>a.name.localeCompare(b.name)).map(row),'<!-- end generated -->'].join('\n');
};
const file=join(server,'CAPABILITIES.md');
test('CAPABILITIES.md matches the registered tools',()=>{
 const text=read(file);const block=/<!-- generated[\s\S]*<!-- end generated -->/;assert.match(text,block);
 if(process.env.UPDATE_CAPABILITIES==='1')writeFileSync(file,text.replace(block,()=>expected()));
 assert.equal(read(file).match(block)[0],expected(),'Run UPDATE_CAPABILITIES=1 make test');
});
const docs=['README.md','README.plugin.md','server-hardened/README.md','server-hardened/SECURITY.md','server-hardened/AGENTS-API.md','server-hardened/OPERATIONS-API.md','server-hardened/INTAKE-API.md','server-hardened/PROVISIONING-API.md'].map(p=>join(root,p));
test('docs state only the current tool counts',()=>{
 for(const doc of docs)for(const m of read(doc).matchAll(/\b(\d+) (?:unique )?tools\b/g))assert.ok([byDefault,allTools.length].includes(Number(m[1])),`${doc} says "${m[0]}"`);
 assert.ok(read(join(root,'README.md')).includes(`**${byDefault} tools** by default and **${allTools.length} tools**`));
});
const skillFiles=d=>readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?skillFiles(join(d,e.name)):e.name.endsWith('.md')?[join(d,e.name)]:[]);
const verb=/`((?:get|list|create|update|delete|run|start|wait|abort|send|answer|search|add|build|clear|inspect|check|merge|move|share|write|read|register|upload|download|export|cancel|batch|duplicate|clone|validate|test|autodetect|configure|attach|detach|wake|shutdown|upsert|remove)_[a-z_]+)`/g;
test('tool names in the skill, README and SECURITY exist',()=>{
 for(const doc of [...skillFiles(join(root,'skills')),join(root,'README.md'),join(server,'SECURITY.md')])for(const m of read(doc).matchAll(verb))assert.ok(names.has(m[1]),`${doc} names unknown tool ${m[1]}`);
});
test('skill references linked from SKILL.md exist and every reference is linked',()=>{
 const dir=join(root,'skills/dataiku-operations');const skill=read(join(dir,'SKILL.md'));const links=[...skill.matchAll(/references\/[a-z-]+\.md/g)].map(m=>m[0]);
 for(const l of links)assert.ok(existsSync(join(dir,l)),l);
 for(const f of readdirSync(join(dir,'references')))assert.ok(links.includes(`references/${f}`),`${f} is not linked`);
});
test('no doc suggests the rejected insecure TLS switch or the removed Python server',()=>{
 for(const p of ['README.md','README.plugin.md','skills/dataiku-operations/SKILL.md','.mcp.json','.env.example','server-hardened/SECURITY.md','server-hardened/CAPABILITIES.md'])assert.doesNotMatch(read(join(root,p)),/DSS_INSECURE_TLS|dataiku_factory|\buv\b|[Cc]obuild/,p);
});
